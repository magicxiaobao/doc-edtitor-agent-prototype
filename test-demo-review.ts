import assert from 'node:assert/strict';
import {createPresetTask} from './src/services/mockData';
import {implementReviewCommentWithText,rebindReviewCommentTargetBlock,applyCoordinationDecision,generateCoordinationDiff} from './src/services/reviewCoordinationService';
import {undoSafeParagraphModification,validateUndoEligibility} from './src/services/draftLifecycleService';
import {runDocumentAudit} from './src/services/mockAuditService';
import {computeTextDiff} from './src/services/diffService';
import type {ReviewComment} from './src/types';
const task=createPresetTask('under_review');
const draft=task.drafts.find(d=>d.id===task.currentDraftId)!;
const source:ReviewComment={id:'REVIEW-NEW',type:'paragraph',reviewer:'审阅乙',content:'精炼第二段',targetBlockId:draft.blocks[0].id,targetVersionId:draft.id,baseParagraphText:draft.blocks[0].content,status:'pending',createdAt:new Date().toISOString()};
task.reviewComments=[source];
const rebound=rebindReviewCommentTargetBlock(task,source.id,draft.blocks[1].id,'主笔甲').updatedTask;
const changed=implementReviewCommentWithText(rebound,source.id,draft.id,'  调整后的第二段。\n','主笔已核实','主笔甲',{expectedBaseContent:draft.blocks[1].content});
assert.equal(changed.workingDraft.blocks[0].content,draft.blocks[0].content);
assert.equal(changed.workingDraft.blocks[1].content,'  调整后的第二段。\n');
assert.equal(changed.updatedTask.reviewComments[0].targetBlockId,source.targetBlockId);
const log=changed.updatedTask.modificationLogs![0];
assert.equal(log.source,'review_implementation');
assert.equal(validateUndoEligibility(changed.updatedTask,changed.workingDraft,log.id,'主笔甲').canUndo,true);
const undone=undoSafeParagraphModification(changed.updatedTask,changed.workingDraft,log.id,'主笔甲');
assert.equal(undone.workingDraft.blocks[1].content,draft.blocks[1].content);
assert.equal(undone.updatedTask.reviewComments[0].status,'pending');
const overall={...source,id:'WHOLE',type:'overall' as const,targetBlockId:undefined};
const overallTask={...task,reviewComments:[overall]};
const whole=implementReviewCommentWithText(overallTask,overall.id,draft.id,'全局意见落实第二段','处理说明','主笔甲',{targetBlockId:draft.blocks[1].id,expectedBaseContent:draft.blocks[1].content});
assert.equal(whole.updatedTask.reviewComments[0].type,'overall');
assert.equal(whole.workingDraft.blocks[0].content,draft.blocks[0].content);
assert.equal(whole.workingDraft.blocks[1].content,'全局意见落实第二段');
const oldText='原文。！！\n\n'.repeat(100),newText=oldText+'新增；；\n';
const diff=computeTextDiff(oldText,newText);
assert.equal(diff.filter(s=>s.type!=='added').map(s=>s.text).join(''),oldText);
assert.equal(diff.filter(s=>s.type!=='removed').map(s=>s.text).join(''),newText);
const coordTask=createPresetTask('under_review');coordTask.reviewComments=coordTask.reviewComments.map((c,i)=>({...c,id:`NEW-COORD-${i}`}));
const coordDraft=coordTask.drafts.find(d=>d.id===coordTask.currentDraftId)!;
const preview=generateCoordinationDiff(coordTask,coordDraft,'compress');
assert(preview.diffPreview.length>0);
const coordinated=applyCoordinationDecision(coordTask,coordDraft.id,{...preview,strategyExplanation:'主笔的实际协调理由'},'主笔甲',coordTask.reviewComments.slice(0,2).map(c=>c.id));
assert.equal(coordinated.updatedTask.reviewComments[0].decisionReason,'主笔的实际协调理由');
assert(coordinated.updatedTask.modificationLogs!.some(l=>l.source==='review_implementation'));
assert.equal(validateUndoEligibility(coordinated.updatedTask,coordinated.workingDraft,coordinated.updatedTask.modificationLogs![0].id,'主笔甲').canUndo,false);
assert(coordinated.updatedTask.reviewComments.slice(0,2).every(c=>c.status==='accepted_pending_implementation'));
const explicit=structuredClone(coordTask);
const firstDiff=preview.diffPreview[0];
explicit.reviewComments[0]={...explicit.reviewComments[0],type:'paragraph',targetBlockId:firstDiff.blockId,suggestionType:'replacement',suggestedChange:firstDiff.proposedText};
explicit.reviewComments[1]={...explicit.reviewComments[1],type:'paragraph',targetBlockId:'UNTOUCHED-BLOCK',suggestionType:'instruction',content:'请核对另一个段落'};
const exact=applyCoordinationDecision(explicit,coordDraft.id,preview,'主笔甲',explicit.reviewComments.slice(0,2).map(c=>c.id));
assert.equal(exact.updatedTask.reviewComments[0].status,'implemented');
assert.equal(exact.updatedTask.reviewComments[1].status,'accepted_pending_implementation');
const auditTask=createPresetTask('under_review'), auditDraft=auditTask.drafts.find(d=>d.id===auditTask.currentDraftId)!;
const template=auditDraft.snapshotMetadata!.factSnapshot!.items![0];
auditDraft.snapshotMetadata!.factSnapshot!.items=[{...template,factId:'A',metric:'任务',value:'10',selectedConflictValue:'10',hasConflict:false},{...template,factId:'B',metric:'重点任务',value:'20',selectedConflictValue:'20',hasConflict:false}];
auditDraft.blocks=[{...auditDraft.blocks[0],content:'重点任务完成20项。',referencedFactIds:['A','B']}];
assert(!runDocumentAudit(auditTask,auditDraft.blocks,auditDraft.id).some(i=>i.type==='conflict_mismatch'));
console.log('PASS: explicit review targets, overall scope, direct-write log/undo, lossless diff and non-hardcoded coordination');
